  '#',
  '#   date      5 | 05 | 11-05 | 2026-11-05 | today | yesterday',
  '#   type      i income    s spend    v invest',
  '#   category  one word, use-dashes-for-spaces',
  '#   amount    1250 | 1,250.50 | 18k | 1.2L',
  '#',
  '#   3 s groceries 4100 big shop',
  '#   today v mutual-fund 15k SIP',
  '#',
  '# :w adds them all.  :q or q cancels.  Lines that fail stay here.',
  '',
}

--- True only for a date that actually exists (rejects 2026-02-31).
local function valid_date(str)
  local y, m, d = str:match '^(%d%d%d%d)%-(%d%d)%-(%d%d)$'
  if not y then return false end
  local t = os.time { year = tonumber(y), month = tonumber(m), day = tonumber(d), hour = 12 }
  return os.date('%Y-%m-%d', t) == str
end

--- Expand a loose date token into YYYY-MM-DD. A bare day or MM-DD fills in
--- from today, which is what you want when catching up on the current month.
local function resolve_date(tok)
  local now = os.date '*t'
  local low = tok:lower()
  if low == 'today' or low == 't' then return os.date '%Y-%m-%d' end
  if low == 'yesterday' or low == 'y' then return os.date('%Y-%m-%d', os.time() - 86400) end
  if tok:match '^%d%d%d%d%-%d%d?%-%d%d?$' then
    local y, m, d = tok:match '^(%d+)%-(%d+)%-(%d+)$'
    return ('%04d-%02d-%02d'):format(tonumber(y), tonumber(m), tonumber(d))
  end
  local m, d = tok:match '^(%d%d?)%-(%d%d?)$'
  if m then return ('%04d-%02d-%02d'):format(now.year, tonumber(m), tonumber(d)) end
  local day = tok:match '^(%d%d?)$'
  if day then return ('%04d-%02d-%02d'):format(now.year, now.month, tonumber(day)) end
  return nil
end

--- 1250 | 1,250.50 | 18k | 1.2L  ->  a number.
local function resolve_amount(tok)
  local body, suffix = tok:match '^([%d,%.]+)([kKlL]?)$'
  if not body then return nil end
  local n = tonumber((body:gsub(',', '')))
  if not n then return nil end
  if suffix:lower() == 'k' then n = n * 1000 end
  if suffix:lower() == 'l' then n = n * 100000 end
  return n
end

local function parse_bulk_line(line)
  local toks = vim.split(trim(line), '%s+', { trimempty = true })
  if #toks < 4 then return nil, 'need at least: date type category amount' end
  local date = resolve_date(toks[1])
  if not date then return nil, 'bad date ' .. vim.inspect(toks[1]) end
  if not valid_date(date) then return nil, 'no such date: ' .. date end
  local ty = TYPE_ALIASES[toks[2]:lower()]
  if not ty then return nil, 'bad type ' .. vim.inspect(toks[2]) .. ' (i/s/v)' end
  local amount = resolve_amount(toks[4])
  if not amount then return nil, 'bad amount ' .. vim.inspect(toks[4]) end
  return {
    date = date,
    type = ty,
    category = (toks[3]:gsub('|', '/')),
    amount = amount,
    note = (table.concat(vim.list_slice(toks, 5), ' '):gsub('|', '/')),
  }
end

local function apply_bulk(ledger, buf, win)
  local good, bad = {}, {}
  for _, line in ipairs(vim.api.nvim_buf_get_lines(buf, 0, -1, false)) do
    if not (is_blank(line) or is_comment(line)) then
      local row, err = parse_bulk_line(line)
      if row then
        table.insert(good, row)
      else
        table.insert(bad, { line = line, err = err })
      end
    end
  end

  if #good == 0 and #bad == 0 then return vim.notify('Nothing to add', vim.log.levels.WARN) end

  if #good > 0 then
    if not vim.api.nvim_buf_is_valid(ledger) then return vim.notify('The ledger buffer is gone', vim.log.levels.ERROR) end
    local lines = {}
    for _, r in ipairs(good) do
      table.insert(lines, ('| %s | %s | %s | %.2f | %s |'):format(r.date, r.type, r.category, r.amount, r.note))
    end
    vim.api.nvim_buf_set_lines(ledger, -1, -1, false, lines)
    -- We are inside a BufWriteCmd and nested autocmds do not fire, so the
    -- ledger's own BufWritePre hook will not run. Sort and realign by hand.
    M.align(ledger, { sort = true })
    vim.api.nvim_buf_call(ledger, function() vim.cmd 'silent write' end)
  end

  vim.bo[buf].modified = false
  if #bad == 0 then
    if win and vim.api.nvim_win_is_valid(win) then vim.api.nvim_win_close(win, true) end
    vim.notify(('Added %d entries'):format(#good))
    return
  end

  local out = vim.deepcopy(BULK_HELP)
  for _, b in ipairs(bad) do
    table.insert(out, '# !! ' .. b.err)
    table.insert(out, b.line)
  end
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, out)
  vim.bo[buf].modified = false
  vim.notify(('Added %d, %d line(s) left to fix'):format(#good, #bad), vim.log.levels.WARN)
end

--- Open a scratch buffer for typing many entries at once; :w commits them.
function M.bulk(ledger)
  ledger = ledger or vim.api.nvim_get_current_buf()
  if vim.bo[ledger].filetype ~= 'budget' then
    M.open()
    ledger = vim.api.nvim_get_current_buf()
  end

  local buf = vim.api.nvim_create_buf(false, true)
  vim.bo[buf].buftype = 'acwrite' -- so :w fires BufWriteCmd instead of writing a file
  vim.bo[buf].bufhidden = 'wipe'
  vim.bo[buf].commentstring = '# %s'
  vim.api.nvim_buf_set_name(buf, 'budget://add')
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, BULK_HELP)
  vim.bo[buf].modified = false

  vim.cmd 'botright 18split'
  local win = vim.api.nvim_get_current_win()
  vim.api.nvim_win_set_buf(win, buf)
  vim.wo[win].winbar = ''
  vim.wo[win].number = false
  vim.wo[win].relativenumber = false
  vim.cmd [[
    syntax clear
    syntax match budgetBulkComment '^\s*#.*$'
    syntax match budgetBulkError   '^\s*# !!.*$'
    highlight default link budgetBulkComment Comment
    highlight default link budgetBulkError   DiagnosticError
  ]]
  vim.api.nvim_win_set_cursor(win, { #BULK_HELP, 0 })

  vim.keymap.set('n', 'q', function()
    if vim.api.nvim_win_is_valid(win) then vim.api.nvim_win_close(win, true) end
  end, { buffer = buf, nowait = true, desc = 'Cancel bulk entry' })

  vim.api.nvim_create_autocmd('BufWriteCmd', {
    buffer = buf,
    desc = 'Commit bulk budget entries',
    callback = function() apply_bulk(ledger, buf, win) end,
  })

  vim.cmd 'startinsert'
end

