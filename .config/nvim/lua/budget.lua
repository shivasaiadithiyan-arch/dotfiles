function M.open()
  vim.fn.mkdir(vim.fs.dirname(M.config.file), 'p')
  vim.cmd.edit(vim.fn.fnameescape(M.config.file))
end

local function syntax()
  vim.cmd [[
    syntax clear
    syntax match budgetComment  '^\s*#.*$'
    syntax match budgetRule     '^\s*|[-: |]\+|\s*$'
    syntax match budgetHeader   '^\s*|\s*Date\s*|.*$'
    syntax match budgetPipe     '|'
    syntax match budgetDate     '\d\{4}-\d\{2}-\d\{2}'
    syntax match budgetIncome   '\<income\>'
    syntax match budgetSpend    '\<spend\>'
    syntax match budgetInvest   '\<invest\>'
    syntax match budgetAmount   '\d\+\.\d\d'
    highlight default link budgetComment Comment
    highlight default link budgetRule    Comment
    highlight default link budgetHeader  Title
    highlight default link budgetPipe    Delimiter
    highlight default link budgetDate    Constant
    highlight default link budgetIncome  DiagnosticOk
    highlight default link budgetSpend   DiagnosticError
    highlight default link budgetInvest  DiagnosticWarn
    highlight default link budgetAmount  Number
  ]]
end

function M.attach(bufnr)
  vim.bo[bufnr].expandtab = true
  vim.bo[bufnr].commentstring = '# %s'
  syntax()

  -- Window-local, so reapply them every time this buffer enters a window.
  local function window_opts()
    vim.wo.winbar = "%{%v:lua.require'budget'.winbar()%}"
    vim.wo.wrap = false
    vim.wo.cursorline = true
  end
  window_opts()
  vim.api.nvim_create_autocmd('BufWinEnter', {
    buffer = bufnr,
    group = vim.api.nvim_create_augroup('budget-win-' .. bufnr, { clear = true }),
    callback = window_opts,
  })

  local function map(lhs, fn, desc) vim.keymap.set('n', lhs, fn, { buffer = bufnr, desc = desc }) end
  map('<leader>ba', M.add, 'Add entry')
  map('<leader>bi', function() M.bulk(bufnr) end, 'Bulk add entries')
  map('<leader>bs', function() M.dashboard(os.date '%Y-%m') end, 'Summary (this month)')
  map('<leader>by', function() M.dashboard(os.date '%Y') end, 'Summary (this year)')
  map('<leader>bt', function() M.dashboard(nil) end, 'Summary (all time)')
  map('<leader>bf', function() M.align(bufnr, { sort = true }) end, 'Format and sort')
  map('<leader>bd', M.delete, 'Delete entry')
  map('<leader>br', M.repeat_entry, 'Repeat entry today')
  map('<leader>bx', function() M.export(os.date '%Y') end, 'Export year to CSV')
  map('<leader>bX', function() M.export(nil) end, 'Export all to CSV')
  map('<leader>bc', M.check, 'Check ledger')

  local ok, wk = pcall(require, 'which-key')
  if ok then wk.add { { '<leader>b', group = 'Budget', buffer = bufnr } } end

  vim.api.nvim_create_autocmd('BufWritePre', {
    buffer = bufnr,
    group = vim.api.nvim_create_augroup('budget-align-' .. bufnr, { clear = true }),
    desc = 'Realign the budget table on save',
    callback = function() M.align(bufnr, { sort = true }) end,
  })
end

function M.setup(opts)
  M.config = vim.tbl_deep_extend('force', M.config, opts or {})
  vim.filetype.add {
    filename = { [M.config.file] = 'budget' },
    pattern = { ['.*/notes/budget/.*%.md'] = 'budget' },
  }
  vim.api.nvim_create_user_command('Budget', function() M.open() end, { desc = 'Open the budget ledger' })
  vim.api.nvim_create_user_command('BudgetAdd', function() M.bulk() end, { desc = 'Add several budget entries at once' })
  vim.api.nvim_create_user_command('BudgetExport', function(a) M.export(a.args ~= '' and a.args or nil) end, { nargs = '?', desc = 'Export the ledger as CSV' })
  vim.api.nvim_create_autocmd('FileType', {
    pattern = 'budget',
    group = vim.api.nvim_create_augroup('budget-ft', { clear = true }),
    callback = function(ev) M.attach(ev.buf) end,
  })
end

return M
