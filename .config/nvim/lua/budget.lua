local MONTHS = { 'January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December' }

local function period_label(period)
  if not period then return 'All time' end
  local y, m = period:match '^(%d%d%d%d)%-(%d%d)$'
  if y then return MONTHS[tonumber(m)] .. ' ' .. y end
  return period
end

local function days_in_month(y, m) return tonumber(os.date('%d', os.time { year = y, month = m + 1, day = 0, hour = 12 })) end

local function shift_month(period, delta)
  local y, m = period:match '^(%d%d%d%d)%-(%d%d)$'
  if not y then return period end
  return os.date('%Y-%m', os.time { year = tonumber(y), month = tonumber(m) + delta, day = 1, hour = 12 })
end

local function breakdown(lines, title, cats, total, budgets)
  if vim.tbl_isempty(cats) then return end
  table.insert(lines, '')
  table.insert(lines, '  ' .. title)
  local keys = sorted_pairs(cats)
  local biggest = cats[keys[1]]
  for _, k in ipairs(keys) do
    local amt = cats[k]
    local line = '    ' .. ljust(k:sub(1, 14), 14) .. ' ' .. bar(amt / biggest) .. ' ' .. rjust(M.money(amt), 15)
    if total > 0 then line = line .. ('  %5.1f%%'):format(amt / total * 100) end
    local limit = budgets and budgets[k]
    if limit and limit > 0 then
      local used = amt / limit * 100
      line = line .. ('   %s %.0f%% of %s'):format(used > 100 and '!!' or 'ok', used, M.money(limit))
    end
    table.insert(lines, line)
  end
end

local function dashboard_lines(rows, budgets, period)
  local t = M.summary(rows, period)
  local L = {}
  local function kv(label, value, note) table.insert(L, '  ' .. ljust(label, 26) .. ' ' .. rjust(value, 18) .. (note and ('   ' .. note) or '')) end

  table.insert(L, ('  %s%s'):format(period_label(period), ('  --  %d entries'):format(t.n)))
  table.insert(L, '')
  kv('Income', M.money(t.income))
  kv('Spends', M.money(t.spend))
  kv('Investments', M.money(t.invest))
  table.insert(L, '  ' .. string.rep('\u{2500}', 46))
  kv('Saved (income - spends)', M.money(t.saved), ('%.1f%% savings rate'):format(t.rate))
  kv('Unallocated cash', M.money(t.net), t.net < 0 and '<- overspent' or nil)

  if t.income > 0 then
    table.insert(L, '')
    table.insert(L, ('    spend %s  %.0f%%'):format(bar(t.spend / t.income, 28), t.spend / t.income * 100))
    table.insert(L, ('    inv   %s  %.0f%%'):format(bar(t.invest / t.income, 28), t.invest / t.income * 100))
  end

  local is_month = (period or ''):match '^%d%d%d%d%-%d%d$' ~= nil
  breakdown(L, 'Spends by category', t.cats.spend, t.spend, is_month and budgets or nil)
  breakdown(L, 'Investments by category', t.cats.invest, t.invest, nil)
  breakdown(L, 'Income by source', t.cats.income, t.income, nil)

  -- Month-by-month trend, for any period spanning more than one month.
  if not is_month then
    local months = {}
    for _, r in ipairs(rows) do
      if not period or r.date:sub(1, #period) == period then
        local key = r.date:sub(1, 7)
        months[key] = months[key] or { income = 0, spend = 0, invest = 0 }
        months[key][r.type] = months[key][r.type] + r.amount
      end
    end
    local keys = vim.tbl_keys(months)
    if #keys > 1 then
      table.sort(keys)
      table.insert(L, '')
      local function trend(month, a, b2, c, d)
        return '  ' .. ljust(month, 9) .. ' ' .. rjust(a, 15) .. ' ' .. rjust(b2, 15) .. ' ' .. rjust(c, 15) .. ' ' .. rjust(d, 15)
      end
      table.insert(L, trend('Month', 'Income', 'Spends', 'Invested', 'Net'))
      for _, k in ipairs(keys) do
        local v = months[k]
        table.insert(L, trend(k, M.money(v.income), M.money(v.spend), M.money(v.invest), M.money(v.income - v.spend - v.invest)))
      end
    end
  end

  -- Burn rate, but only for a month that is actually in progress.
  local y, m = (period or ''):match '^(%d%d%d%d)%-(%d%d)$'
  if is_month and y and t.spend > 0 then
    local total_days = days_in_month(tonumber(y), tonumber(m))
    local elapsed = (period == os.date '%Y-%m') and tonumber(os.date '%d') or total_days
    local per_day = t.spend / elapsed
    table.insert(L, '')
    table.insert(L, ('  Pace  day %d/%d  --  %s/day  --  projected %s'):format(elapsed, total_days, M.money(per_day), M.money(per_day * total_days)))
  end

  table.insert(L, '')
  table.insert(L, '  [ ]  month    y  year    t  all time    a  add    q  close')
  return L
end

local state = { win = nil, buf = nil, period = nil, source = nil }

local function close_dashboard()
  if state.win and vim.api.nvim_win_is_valid(state.win) then vim.api.nvim_win_close(state.win, true) end
  state.win, state.buf = nil, nil
end

--- Open (or refresh) the floating summary for `period`.
function M.dashboard(period)
  local src = state.source
  if not src or not vim.api.nvim_buf_is_valid(src) then
    src = vim.api.nvim_get_current_buf()
    state.source = src
  end
  local rows, _, budgets, errors = M.parse(src)
  if not require_clean(src, errors) then return end

  state.period = period
  local lines = dashboard_lines(rows, budgets, period)
  local width, height = 0, #lines
  for _, l in ipairs(lines) do
    width = math.max(width, vim.fn.strdisplaywidth(l))
  end
  width = math.min(width + 2, vim.o.columns - 4)
  height = math.min(height, vim.o.lines - 6)

  local buf = (state.buf and vim.api.nvim_buf_is_valid(state.buf)) and state.buf or vim.api.nvim_create_buf(false, true)
  state.buf = buf
  vim.bo[buf].modifiable = true
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
  vim.bo[buf].modifiable = false
  vim.bo[buf].filetype = 'budgetsummary'

  if state.win and vim.api.nvim_win_is_valid(state.win) then
    vim.api.nvim_win_set_config(state.win, {
      relative = 'editor',
      width = width,
      height = height,
      row = math.floor((vim.o.lines - height) / 2) - 1,
      col = math.floor((vim.o.columns - width) / 2),
    })
  else
    state.win = vim.api.nvim_open_win(buf, true, {
      relative = 'editor',
      width = width,
      height = height,
      row = math.floor((vim.o.lines - height) / 2) - 1,
      col = math.floor((vim.o.columns - width) / 2),
      style = 'minimal',
      border = 'rounded',
      title = ' Budget ',
      title_pos = 'center',
    })
    vim.wo[state.win].cursorline = false

    local function map(lhs, fn) vim.keymap.set('n', lhs, fn, { buffer = buf, nowait = true, silent = true }) end
    map('q', close_dashboard)
    map('<Esc>', close_dashboard)
    map('[', function() M.dashboard(shift_month(state.period or os.date '%Y-%m', -1)) end)
    map(']', function() M.dashboard(shift_month(state.period or os.date '%Y-%m', 1)) end)
    map('y', function() M.dashboard(os.date '%Y') end)
    map('t', function() M.dashboard(nil) end)
    map('a', function()
      close_dashboard()
      M.add()
    end)
  end
  vim.api.nvim_win_set_buf(state.win, buf)
end

