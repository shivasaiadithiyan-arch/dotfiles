--- Aggregate rows over a period prefix ('2026-11', '2026', or nil for all time).
function M.summary(rows, period)
  local t = { income = 0, spend = 0, invest = 0, n = 0, cats = { income = {}, spend = {}, invest = {} }, days = {} }
  for _, r in ipairs(rows) do
    if not period or r.date:sub(1, #period) == period then
      t[r.type] = t[r.type] + r.amount
      local c = r.category ~= '' and r.category:lower() or 'uncategorised'
      t.cats[r.type][c] = (t.cats[r.type][c] or 0) + r.amount
      t.days[r.date] = true
      t.n = t.n + 1
    end
  end
  t.outflow = t.spend + t.invest
  t.net = t.income - t.outflow -- left unallocated
  t.saved = t.income - t.spend -- invested money is still yours
  t.rate = t.income > 0 and (t.saved / t.income * 100) or 0
  return t
end

local function sorted_pairs(tbl)
  local keys = vim.tbl_keys(tbl)
  table.sort(keys, function(a, b) return tbl[a] > tbl[b] end)
  return keys
end

