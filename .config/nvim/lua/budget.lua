local function known_categories(rows, ty)
  local seen, out = {}, {}
  for i = #rows, 1, -1 do -- most recent first
    local r = rows[i]
    if r.type == ty and r.category ~= '' and not seen[r.category:lower()] then
      seen[r.category:lower()] = true
      table.insert(out, r.category)
    end
  end
  return out
end

local function append_row(bufnr, row)
  local rows, comments, _, errors = M.parse(bufnr)
  if not require_clean(bufnr, errors) then return end
  table.insert(rows, row)
  table.sort(rows, function(a, b)
    if a.date ~= b.date then return a.date < b.date end
    return (a.lnum or math.huge) < (b.lnum or math.huge)
  end)
  vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, render(rows, comments))
  for i, line in ipairs(vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)) do
    if line:find(row.date, 1, true) and line:find(row.category, 1, true) then vim.api.nvim_win_set_cursor(0, { i, 0 }) end
  end
  vim.notify(('Added %s %s %s'):format(row.type, M.money(row.amount), row.category))
end

--- Prompt for a new entry: date, type, category, amount, note.
function M.add()
  local bufnr = vim.api.nvim_get_current_buf()
  if vim.bo[bufnr].filetype ~= 'budget' then
    M.open()
    bufnr = vim.api.nvim_get_current_buf()
  end
  local rows = M.parse(bufnr)

  vim.ui.input({ prompt = 'Date: ', default = os.date '%Y-%m-%d' }, function(date)
    if not date or trim(date) == '' then return end
    date = trim(date)
    if not date:match '^%d%d%d%d%-%d%d%-%d%d$' then return vim.notify('Date must be YYYY-MM-DD', vim.log.levels.ERROR) end

    vim.ui.select(M.config.types, { prompt = 'Type' }, function(ty)
      if not ty then return end
      local cats = known_categories(rows, ty)
      table.insert(cats, '[new category]')

      local function with_category(cat)
        vim.ui.input({ prompt = 'Amount: ' }, function(amt)
          local n = tonumber((trim(amt or ''):gsub('[^%d%.%-]', '')))
          if not n then return vim.notify('Amount must be a number', vim.log.levels.ERROR) end
          vim.ui.input(
            { prompt = 'Note: ' },
            function(note) append_row(bufnr, { date = date, type = ty, category = cat, amount = n, note = trim((note or ''):gsub('|', '/')) }) end
          )
        end)
      end

      vim.ui.select(cats, { prompt = ty:gsub('^%l', string.upper) .. ' category' }, function(cat)
        if not cat then return end
        if cat == '[new category]' then
          vim.ui.input({ prompt = 'New category: ' }, function(new)
            if not new or trim(new) == '' then return end
            with_category(trim(new):gsub('|', '/'))
          end)
        else
          with_category(cat)
        end
      end)
    end)
  end)
end

--- Delete the entry under the cursor.
function M.delete()
  local lnum = vim.api.nvim_win_get_cursor(0)[1]
  local line = vim.api.nvim_buf_get_lines(0, lnum - 1, lnum, false)[1] or ''
  if is_sep(line) or is_comment(line) or is_blank(line) or (cells(line) or { '' })[1]:lower() == 'date' then
    return vim.notify('Not an entry line', vim.log.levels.WARN)
  end
  vim.api.nvim_buf_set_lines(0, lnum - 1, lnum, false, {})
  M.align(0)
  vim.notify 'Entry deleted (u to undo)'
end

--- Duplicate the entry under the cursor with today's date -- for recurring spends.
function M.repeat_entry()
  local lnum = vim.api.nvim_win_get_cursor(0)[1]
  local c = cells(vim.api.nvim_buf_get_lines(0, lnum - 1, lnum, false)[1] or '')
  if not c or not (c[1] or ''):match '^%d%d%d%d%-%d%d%-%d%d$' then return vim.notify('Not an entry line', vim.log.levels.WARN) end
  local amount = tonumber(((c[4] or ''):gsub('[^%d%.%-]', '')))
  if not amount then return vim.notify('Cannot read the amount on this line', vim.log.levels.WARN) end
  append_row(0, { date = os.date '%Y-%m-%d', type = (c[2] or ''):lower(), category = c[3] or '', amount = amount, note = c[5] or '' })
end

