-- winbar: live totals for the month under the cursor
---------------------------------------------------------------------------

local winbar_cache = {}

local function month_at_cursor(rows)
  local lnum = vim.api.nvim_win_get_cursor(0)[1]
  local best
  for _, r in ipairs(rows) do
    if r.lnum <= lnum then best = r.date:sub(1, 7) end
  end
  return best or os.date '%Y-%m'
end

function M.winbar()
  local buf = vim.api.nvim_get_current_buf()
  local tick = vim.api.nvim_buf_get_changedtick(buf)
  local rows, _, _, errors = M.parse(buf)
  local month = month_at_cursor(rows)
  local key = tick .. ':' .. month
  if winbar_cache[buf] and winbar_cache[buf].key == key then return winbar_cache[buf].text end

  local text
  if #errors > 0 then
    text = ('%%#DiagnosticError# %d bad line(s) -- <leader>bc to check %%*'):format(#errors)
  else
    local t = M.summary(rows, month)
    text = table.concat {
      ' %#Title#' .. month .. '%*  ',
      '%#DiagnosticOk#in%* ' .. M.money(t.income),
      '  %#DiagnosticError#out%* ' .. M.money(t.spend),
      '  %#DiagnosticWarn#inv%* ' .. M.money(t.invest),
      '  %#Title#net%* ' .. M.money(t.net),
      ('  %%#Comment#(%.0f%%%% saved)%%*'):format(t.rate),
    }
  end
  winbar_cache[buf] = { key = key, text = text }
  return text
end

