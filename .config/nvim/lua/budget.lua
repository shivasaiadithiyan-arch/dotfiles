--- Write the ledger out as CSV for Excel, Sheets or anything else.
function M.export(period)
  local rows, _, _, errors = M.parse(0)
  if not require_clean(0, errors) then return end
  local function q(v)
    v = tostring(v)
    if v:find '[",\n]' then return '"' .. v:gsub('"', '""') .. '"' end
    return v
  end
  local out = { 'date,type,category,amount,note' }
  for _, r in ipairs(rows) do
    if not period or r.date:sub(1, #period) == period then
      table.insert(out, table.concat({ r.date, r.type, q(r.category), string.format('%.2f', r.amount), q(r.note) }, ','))
    end
  end
  local path = vim.fs.dirname(M.config.file) .. '/export-' .. (period or 'all') .. '.csv'
  vim.fn.writefile(out, path)
  vim.notify(('Exported %d entries to %s'):format(#out - 1, path))
end

--- Validate the ledger and report.
function M.check()
  local rows, _, budgets, errors = M.parse(0)
  if #errors > 0 then return require_clean(0, errors) end
  vim.notify(('Ledger is clean: %d entries, %d budgets set'):format(#rows, vim.tbl_count(budgets)))
end

