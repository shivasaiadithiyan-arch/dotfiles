-- budget.lua -- a spreadsheet-ish expense tracker that lives in a plain text file.
--
-- The ledger is a markdown table, so it stays greppable, diffable and readable
-- without this plugin -- but inside nvim it behaves like a sheet: columns
-- realign on save, a winbar shows live running totals, and a dashboard gives
-- the month's breakdown with per-category budgets.
--
-- Entries go in one at a time with <leader>ba, or a batch at a time with
-- <leader>bi, which opens a scratch buffer of terse lines ("3 s rent 18k")
-- that :w turns into rows.
--
--   Ledger:  ~/notes/budget/ledger.md   (override with $BUDGET_FILE)
--   Toggle:  $mod+e  (i3 scratchpad, see ~/.config/i3/budget.sh)

local M = {}

local HEADER = { 'Date', 'Type', 'Category', 'Amount', 'Note' }
local ALIGN = { 'left', 'left', 'left', 'right', 'left' }

M.config = {
  file = vim.env.BUDGET_FILE or (vim.env.HOME .. '/notes/budget/ledger.md'),
  currency = '\u{20B9}',
  -- Indian digit grouping (1,23,456) rather than western (123,456).
  grouping = 'indian',
  types = { 'income', 'spend', 'invest' },
  bar_width = 16,
}

---------------------------------------------------------------------------
-- formatting
---------------------------------------------------------------------------

local function trim(s) return (s:gsub('^%s*(.-)%s*$', '%1')) end

local function group(int)
  if M.config.grouping ~= 'indian' then return (int:reverse():gsub('(%d%d%d)', '%1,'):reverse():gsub('^,', '')) end
  if #int <= 3 then return int end
  local parts, rest = { int:sub(-3) }, int:sub(1, -4)
  while #rest > 2 do
    table.insert(parts, 1, rest:sub(-2))
    rest = rest:sub(1, -3)
  end
  if #rest > 0 then table.insert(parts, 1, rest) end
  return table.concat(parts, ',')
end

--- Format a number as currency, e.g. -12345.5 -> "-₹12,345.50".
function M.money(n)
  local sign = n < 0 and '-' or ''
  local s = string.format('%.2f', math.abs(n))
  local int, frac = s:match '^(%d+)%.(%d+)$'
  return sign .. M.config.currency .. group(int) .. '.' .. frac
end

local function ljust(s, n)
  local gap = n - vim.fn.strdisplaywidth(s)
  return gap > 0 and (s .. string.rep(' ', gap)) or s
end

local function rjust(s, n)
  local gap = n - vim.fn.strdisplaywidth(s)
  return gap > 0 and (string.rep(' ', gap) .. s) or s
end

local function bar(frac, width)
  width = width or M.config.bar_width
  frac = math.max(0, math.min(1, frac))
  local filled = math.floor(frac * width + 0.5)
  return string.rep('\u{2588}', filled) .. string.rep('\u{2591}', width - filled)
end

---------------------------------------------------------------------------
-- parsing
---------------------------------------------------------------------------

local function is_blank(l) return l:match '^%s*$' ~= nil end
local function is_comment(l) return l:match '^%s*#' ~= nil end
local function is_sep(l) return l:match '^%s*|[%s%-:|]+$' ~= nil end

local function cells(line)
  local body = line:match '^%s*|(.*)|%s*$'
  if not body then return nil end
  local out = {}
  for field in (body .. '|'):gmatch '([^|]*)|' do
    table.insert(out, trim(field))
  end
  return out
end

--- Parse a buffer into rows, passthrough comments, budgets and errors.
--- Rows are validated: a malformed line becomes an error rather than silently
--- vanishing, because this file is the user's only copy of their money.
function M.parse(bufnr)
  bufnr = bufnr or 0
  local rows, comments, budgets, errors = {}, {}, {}, {}
  for i, line in ipairs(vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)) do
    if is_blank(line) or is_sep(line) then -- structural, regenerated by align()
    elseif is_comment(line) then
      table.insert(comments, trim(line))
      local cat, amt = line:match '^%s*#%s*budget%s+([%w_%-]+)%s+([%d%.]+)'
      if cat then budgets[cat:lower()] = tonumber(amt) end
    else
      local c = cells(line)
      if not c then
        table.insert(errors, { lnum = i, msg = 'not a table row: ' .. trim(line) })
      elseif (c[1] or ''):lower() ~= 'date' then -- skip the header row
        local date = c[1] or ''
        local ty = (c[2] or ''):lower()
        local amount = tonumber(((c[4] or ''):gsub('[^%d%.%-]', '')))
        if not date:match '^%d%d%d%d%-%d%d%-%d%d$' then
          table.insert(errors, { lnum = i, msg = 'bad date ' .. vim.inspect(date) .. ' (want YYYY-MM-DD)' })
        elseif not vim.tbl_contains(M.config.types, ty) then
          table.insert(errors, { lnum = i, msg = 'bad type ' .. vim.inspect(ty) .. ' (want ' .. table.concat(M.config.types, '/') .. ')' })
        elseif not amount then
          table.insert(errors, { lnum = i, msg = 'bad amount ' .. vim.inspect(c[4] or '') })
        else
          table.insert(rows, { lnum = i, date = date, type = ty, category = (c[3] or ''), amount = amount, note = (c[5] or '') })
        end
      end
    end
  end
  return rows, comments, budgets, errors
end

--- Report parse errors and jump to the first. Returns true if the buffer is clean.
local function require_clean(bufnr, errors)
  if #errors == 0 then return true end
  bufnr = (bufnr == 0) and vim.api.nvim_get_current_buf() or bufnr
  local msg = { ('%d line(s) in the ledger could not be read:'):format(#errors) }
  for _, e in ipairs(errors) do
    table.insert(msg, ('  line %d: %s'):format(e.lnum, e.msg))
  end
  vim.notify(table.concat(msg, '\n'), vim.log.levels.ERROR)
  if vim.api.nvim_get_current_buf() == bufnr then vim.api.nvim_win_set_cursor(0, { errors[1].lnum, 0 }) end
  return false
end

---------------------------------------------------------------------------
-- the sheet: align and sort
---------------------------------------------------------------------------

local function render(rows, comments)
  local data = {}
  for _, r in ipairs(rows) do
    table.insert(data, { r.date, r.type, r.category, string.format('%.2f', r.amount), r.note })
  end

  local w = {}
  for i, h in ipairs(HEADER) do
    w[i] = vim.fn.strdisplaywidth(h)
  end
  for _, d in ipairs(data) do
    for i, v in ipairs(d) do
      w[i] = math.max(w[i], vim.fn.strdisplaywidth(v))
    end
  end

  local function row(d)
    local parts = {}
    for i = 1, #HEADER do
      local v = d[i] or ''
      local gap = string.rep(' ', w[i] - vim.fn.strdisplaywidth(v))
      parts[i] = ALIGN[i] == 'right' and (gap .. v) or (v .. gap)
    end
    return '| ' .. table.concat(parts, ' | ') .. ' |'
  end

  local out = {}
  vim.list_extend(out, comments)
  if #comments > 0 then table.insert(out, '') end
  table.insert(out, row(HEADER))
  local seps = {}
  for i = 1, #HEADER do
    seps[i] = ALIGN[i] == 'right' and (string.rep('-', w[i] - 1) .. ':') or string.rep('-', w[i])
  end
  table.insert(out, '| ' .. table.concat(seps, ' | ') .. ' |')
  for _, d in ipairs(data) do
    table.insert(out, row(d))
  end
  return out
end

--- Re-pad every column to a common width. Refuses on a malformed buffer.
function M.align(bufnr, opts)
  bufnr = bufnr or 0
  opts = opts or {}
  local rows, comments, _, errors = M.parse(bufnr)
  if not require_clean(bufnr, errors) then return false end
  if opts.sort then table.sort(rows, function(a, b)
    if a.date ~= b.date then return a.date < b.date end
    return a.lnum < b.lnum
  end) end
  local out = render(rows, comments)
  if not vim.deep_equal(out, vim.api.nvim_buf_get_lines(bufnr, 0, -1, false)) then
    -- Only this buffer's own window has a view worth preserving.
    local onscreen = vim.api.nvim_get_current_buf() == ((bufnr == 0) and vim.api.nvim_get_current_buf() or bufnr)
    local view = onscreen and vim.fn.winsaveview() or nil
    vim.api.nvim_buf_set_lines(bufnr, 0, -1, false, out)
    if view then vim.fn.winrestview(view) end
  end
  return true
end

